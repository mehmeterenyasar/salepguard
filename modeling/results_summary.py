"""Generate docs/results_summary.md from metrics.csv and range_change.csv (no hand-typed numbers).

    python modeling/results_summary.py
"""

from __future__ import annotations

import pandas as pd
from sdm import OUT, ROOT

BASE = ROOT / "outputs" / "baseline" / "metrics.csv"


def nice(s: str) -> str:
    g, e = s.split("_", 1)
    return f"*{g.capitalize()} {e}*"


def main() -> None:
    m = pd.read_csv(OUT / "metrics.csv")
    rc = pd.read_csv(OUT / "range_change.csv")
    b = pd.read_csv(BASE) if BASE.exists() else None
    n = len(m)
    gap = m["auc_random_cv"] - m["auc_mean"]
    excl = m[~m["include_in_index"]]
    lines = ["# Results summary (final model)", "",
             "_Generated by `modeling/results_summary.py` from `outputs/models/metrics.csv` and "
             "`outputs/models/range_change.csv`. Do not edit numbers by hand._", ""]
    lines.append(
        f"1. **Spatial validation.** Across {n} species, mean spatial-block AUC is {m['auc_mean'].mean():.2f} "
        f"(range {m['auc_mean'].min():.2f}–{m['auc_mean'].max():.2f}), TSS {m['tss_mean'].mean():.2f}, "
        f"continuous Boyce index {m['cbi_mean'].mean():.2f}, 10 % omission rate {m['omission10_mean'].mean():.2f} "
        f"(expected 0.10 without overfitting).")
    lines.append(
        f"2. **Random CV is optimistic.** With the same settings, random 5-fold CV gives mean AUC "
        f"{m['auc_random_cv'].mean():.2f}, on average {gap.mean():+.3f} higher than spatial CV "
        f"(largest gap {gap.max():+.3f} for {nice(m.loc[gap.idxmax(), 'species_slug'])})."
        + (f" The baseline (random CV, untuned) reported mean AUC {b['auc_mean'].mean():.2f}." if b is not None else ""))
    fcs = m["fc"].value_counts().to_dict()
    lines.append(
        f"3. **Model complexity.** Tuning selected feature classes {', '.join(f'{k}: {v}' for k, v in fcs.items())} "
        f"and median regularisation multiplier {m['rm'].median():g}.")
    best = m.sort_values("auc_mean").iloc[-1]
    worst = m.sort_values("auc_mean").iloc[0]
    lines.append(
        f"4. **Best and worst.** Best: {nice(best['species_slug'])} (spatial AUC {best['auc_mean']:.2f}); "
        f"worst: {nice(worst['species_slug'])} ({worst['auc_mean']:.2f}). "
        + (f"{len(excl)} species fail the quality rule and are excluded from the risk index: "
           + "; ".join(f"{nice(r.species_slug)} ({r.exclusion_reason})" for r in excl.itertuples()) + "."
           if len(excl) else "All species pass the quality rule (CBI ≥ 0, spatial AUC ≥ 0.6, null p ≤ 0.05 where tested)."))
    nm = m.dropna(subset=["null_model_p"])
    if len(nm) and (nm["null_model_p"] == nm["null_model_p"].min()).all():
        lines.append(
            f"5. **Null models.** All {len(nm)} species beat a bias-aware null model (random target-group cells, "
            f"same settings and spatial CV): p = {nm['null_model_p'].iloc[0]:.2f}, the smallest value possible with 49 null "
            f"models. Even the two excluded species carry real signal, just too little (AUC < 0.6) to rely on.")
    elif len(nm):
        lines.append(
            f"5. **Null models.** For the {len(nm)} species tested, observed spatial AUC beats a bias-aware null "
            f"model with p = " + ", ".join(f"{r.null_model_p:.2f} ({nice(r.species_slug)})" for r in nm.itertuples()) + ".")
    f = rc[rc["dispersal"] == "full"]
    k = 6 if len(nm) else 5
    for ssp, lab in [("ssp245", "SSP2-4.5"), ("ssp585", "SSP5-8.5")]:
        s = f[f["scenario"] == ssp]
        nd = rc[(rc["dispersal"] == "none") & (rc["scenario"] == ssp)]
        lines.append(
            f"{k}. **Climate change, {lab} 2041–2060 (Turkey).** Median change in suitable area "
            f"{s['change_pct'].median():+.0f} % with full dispersal (range {s['change_pct'].min():+.0f} to "
            f"{s['change_pct'].max():+.0f} %), {nd['change_pct'].median():+.0f} % with no dispersal; "
            f"{(s['change_pct'] < 0).sum()} of {len(s)} species lose area. Restricted to analog climate "
            f"(MESS ≥ 0) the median change is {s['change_pct_analog_only'].median():+.0f} %; "
            f"{s['turkey_nonanalog_pct'].median():.0f} % of Turkey is non-analog for the median species.")
        k += 1
    lines += ["", "Caveats: suitability is relative, background is not absence, eastern Anatolia and *Dactylorhiza* "
              "are missing; see `docs/limitations.md`."]
    (ROOT / "docs" / "results_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
